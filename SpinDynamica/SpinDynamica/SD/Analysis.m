(* ::Input::Initialization:: *)
CorrelatedEigensystems[Qmats_,opts___Rule,{"2","2"}]:=Module[
    {count=Length[Qmats],values,vectors,previousValues,previousVectors,
     valueHistory,vectorHistory,realDistance,imagDistance,vectorOverlap,overlap,
     order,normalizeRows,k},
    CheckAbort[
        If[count==0,Return[$Failed]];
        valueHistory=ConstantArray[Null,count];
        vectorHistory=ConstantArray[Null,count];
        normalizeRows[rows_]:=(#/Max[#+10^-10]&)/@rows;
        Do[
            {values,vectors}=Chop[Eigensystem[Qmats[[k]]]];
            vectors=SparseArray[vectors];
            If[k>1,
                realDistance=Abs[Outer[Subtract,Re[previousValues],Re[values]]];
                imagDistance=Abs[Outer[Subtract,Im[previousValues],Im[values]]];
                vectorOverlap=Chop[Abs[Normal[previousVectors . ConjugateTranspose[vectors]]]];
                overlap=2-(normalizeRows[realDistance]+normalizeRows[imagDistance])+normalizeRows[vectorOverlap];
                order=Flatten[Position[#,Max[#],{1},Heads->False]&/@overlap];
                If[Length[order]!=Length[values] || !DuplicateFreeQ[order],
                    order=OptimalBipartiteGraphMatching[1-overlap/3]
                ];
                values=values[[order]];
                vectors=vectors[[order]]
            ];
            valueHistory[[k]]=SparseArray[values];
            vectorHistory[[k]]=vectors;
            previousValues=values;
            previousVectors=vectors,
            {k,count}
        ];
        {valueHistory,vectorHistory},
        Null
    ]
]


