(* Rotations on distinct spins commute. Keep each spin's original factor order. *)
zeemanPulseBlocks[rotations_List,spins_List]:=Module[{local,cached=<||>,groups,spinLabels=First/@spins},
    If[!AllTrue[rotations,MatchQ[#,{_,{_?NumericQ,"x"|"y"|"z"}}|HoldPattern[opR[_,{_?NumericQ,"x"|"y"|"z"}]]] && MemberQ[spinLabels,First[#]]&],
        Return[$Failed]];
    groups=Dispatch[Append[(First[First[#]]->#)& /@ GatherBy[rotations,First],_->{}]];
    local[spin_,angle_,axis_]:=With[{key=Hold[Last[spin],angle,axis]},
        If[KeyExistsQ[cached,key],cached[key],
            cached[key]=MatrixExp[N[-I angle MatrixRepresentation[opI[First[spin],axis],ZeemanBasis[{spin}]]]]]];
    Function[spin,With[{factors=Replace[First[spin],groups]},
        If[factors==={},None,
            With[{mats=(local[spin,#[[2,1]],#[[2,2]]]& /@ factors)},
                Fold[Dot,First[mats],Rest[mats]]]]]] /@ spins
];

zeemanPulseProduct[rotations_List,spins_]:=Module[{blocks,denseOrId},
    blocks=zeemanPulseBlocks[rotations,spins];
    If[blocks===$Failed,Return[$Failed]];
    denseOrId=MapThread[If[#1===None,IdentityMatrix[2 Last[#2]+1,SparseArray],#1]&,{blocks,spins}];
    If[Length[denseOrId]===1,First[denseOrId],KroneckerProduct@@Reverse[denseOrId]]
];

applySingleSpinMatrixToVector[v_List,u_?MatrixQ,dLeft_Integer,dk_Integer,dRight_Integer]:=Which[
    dLeft===1 && dRight===1, u . v,
    dLeft===1, Flatten[u . ArrayReshape[v,{dk,dRight}]],
    dRight===1, Flatten[ArrayReshape[v,{dLeft,dk}] . Transpose[u]],
    True, Flatten[Transpose[u . Transpose[ArrayReshape[v,{dLeft,dk,dRight}],{2,1,3}],{2,1,3}]]
];

applyFactoredPulseToStateVector[vec_List,uList_List,dims_List]:=Module[{d=Times@@dims,v=Normal[vec],dRight=1,dLeft,dk,u},
    If[Length[v]=!=d || Length[uList]=!=Length[dims],Return[$Failed]];
    Do[
        dk=dims[[k]]; dLeft=Quotient[d,dRight*dk]; u=uList[[k]];
        If[u=!=None, v=applySingleSpinMatrixToVector[v,Normal[u],dLeft,dk,dRight]];
        dRight*=dk,
        {k,Length[dims]}
    ];
    v
];

applyFactoredPulseToDensityMatrix[rho_?MatrixQ,uList_List,dims_List]:=Module[{d=Times@@dims,v=Flatten[Normal[rho]],dRight=1,dLeft,dk,u},
    If[Dimensions[rho]=!={d,d} || Length[uList]=!=Length[dims],Return[$Failed]];
    Do[
        dk=dims[[k]]; dLeft=Quotient[d,dRight*dk]; u=uList[[k]];
        If[u=!=None,
            u=Normal[u];
            v=applySingleSpinMatrixToVector[v,u,dLeft,dk,dRight*d];
            v=applySingleSpinMatrixToVector[v,Conjugate[u],d*dLeft,dk,dRight]
        ];
        dRight*=dk,
        {k,Length[dims]}
    ];
    ArrayReshape[v,{d,d}]
];

