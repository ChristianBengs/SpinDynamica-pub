(* Retain the full system for callers whose solver options can observe its dimension or mesh. *)
canReduceLinearSystemQ[settings_List]:=!AnyTrue[settings,MatchQ[#,
    HoldPattern[(Rule|RuleDelayed)[Method|NormFunction,Except[Automatic]]] |
    HoldPattern[(Rule|RuleDelayed)[EvaluationMonitor|StepMonitor,Except[None]]]]&];

solveFinalLinearEquation[generator_,initial_,clock_Symbol,{ta_,tb_},settings_List]:=
Module[{y,shape=Dimensions[initial],state,variables,rhs,result},
    variables=Flatten[Array[y,shape]];
    state=ArrayReshape[Through[variables[clock]],shape];
    rhs=Flatten[Normal[generator . state]];
    result=NDSolveValue[{D[Flatten[state],clock]==rhs,(Flatten[state]/.clock->ta)==Flatten[Normal[initial]]},
        Evaluate[Through[variables[tb]]],{clock,ta,tb},Evaluate[Sequence@@settings]];
    If[VectorQ[result,NumericQ] && Length[result]===Length[variables],ArrayReshape[result,shape],$Failed]
];

exactZeroQ[x_]:=x===0 || (NumberQ[x] && TrueQ[Sign[x]==0]);

(* The Zeeman digits count the first spin fastest. Subtract traces to make equal local fields reusable.
   Reconstruct the complete matrix before accepting the decomposition, including diagonal couplings. *)
separableSpinHamiltonian[mat_,basis_]:=Module[{dims,h,a,strides,blocks,shift,ids,reconstructed,residual},
    If[!MatchQ[basis,HoldPattern@ZeemanBasis[{{_,_}..},___Rule]],Return[$Failed]];
    dims=(2 Last[#]+1)& /@ First[basis]; h=Times@@dims;
    If[Length[dims]<2 || Dimensions[mat]=!={h,h},Return[$Failed]];
    a=SparseArray[mat];
    If[!exactZeroQ[a["ImplicitValue"]] || a["ExplicitLength"]>h (1+Total[dims-1]),Return[$Failed]];
    strides=Most[FoldList[Times,1,dims]];
    blocks=MapThread[Function[{d,s},With[{ix=1+s Range[0,d-1]},
        With[{sub=Normal[a[[ix,ix]]]},Expand[sub-(Tr[sub]/d) IdentityMatrix[d]]]]],{dims,strides}];
    shift=Expand[a[[1,1]]-Total[(#[[1,1]]& /@ blocks)]];
    blocks[[1]]=Expand[First[blocks]+shift IdentityMatrix[First[dims]]];
    ids=IdentityMatrix[#,SparseArray]& /@ dims;
    reconstructed=Total[MapIndexed[KroneckerProduct@@Reverse[ReplacePart[ids,First[#2]->SparseArray[#1]]]&,
        blocks]];
    residual=SparseArray[a-reconstructed];
    If[AllTrue[Prepend[residual["ExplicitValues"],residual["ImplicitValue"]],exactZeroQ[Expand[#]]&],
        blocks,$Failed]
];

(* All columns of a diagonal fundamental solution are specified by its diagonal. *)
diagonalGeneratorQ[m_]:=If[Head[m]===SparseArray,
    exactZeroQ[m["ImplicitValue"]] && AllTrue[m["ExplicitPositions"],First[#]===Last[#]&],
    TrueQ[DiagonalMatrixQ[m,Tolerance->0]]];

(* Invariant coordinate subspaces of a time-dependent generator. An entry
   that vanishes at a sample time is still an edge if its expression is nonzero. *)
sectorPropagator[g_SparseArray,clock_Symbol,interval_,settings_List]:=Module[
    {n=Length[g],edges,groups,singletons,blocks,solve,entries,diagonal},
    If[n<4 || !exactZeroQ[g["ImplicitValue"]] || g["ExplicitLength"]>n (n+1)/2,Return[$Failed]];
    edges=Select[g["ExplicitPositions"],First[#]=!=Last[#]&];
    groups=ConnectedComponents[Graph[Range[n],UndirectedEdge@@@edges]];
    If[Length[groups]<2,Return[$Failed]];
    singletons=Flatten[Select[groups,Length[#]===1&]];
    blocks=Select[groups,Length[#]>1&];
    solve[a_]:=solve[a]=solveFinalLinearEquation[a,IdentityMatrix[Length[a]],clock,interval,settings];
    entries=Function[ix,With[{m=solve[g[[ix,ix]]]},
        If[m===$Failed,$Failed,Flatten[Table[{ix[[i]],ix[[j]]}->m[[i,j]],{i,Length[ix]},{j,Length[ix]}],1]]]] /@ blocks;
    If[MemberQ[entries,$Failed],Return[$Failed]];
    If[singletons=!={},
        diagonal=solveFinalLinearEquation[g[[singletons,singletons]],ConstantArray[1,Length[singletons]],clock,interval,settings];
        If[diagonal===$Failed,Return[$Failed]];
        AppendTo[entries,MapThread[{#1,#1}->#2&,{singletons,diagonal}]]];
    SparseArray[Join@@entries,{n,n}]
];

piecewiseConstantPropagator[generator_,clock_Symbol,{ta_,tb_},settings_List]:=Module[
    {n=Length[generator],entries,gNorm,ifCalls,interiorMin,interiorMax,breakpoints,knots,u,t0,t1,k,tMid,dt,gMid,stepU,b0,b1},
    If[n===0 || !NumericQ[ta] || !NumericQ[tb] || !canReduceLinearSystemQ[settings] ||
        !FreeQ[settings,HoldPattern[WorkingPrecision->Except[MachinePrecision|Automatic]]],
        Return[$Failed]];
    If[TrueQ[tb==ta],Return[IdentityMatrix[n]]];
    entries=If[Head[generator]===SparseArray,
        Prepend[generator["ExplicitValues"],generator["ImplicitValue"]],
        generator];
    ifCalls=Cases[entries,HoldPattern[InterpolatingFunction[___][_]],Infinity];
    If[ifCalls==={},Return[$Failed]];
    If[!AllTrue[ifCalls,With[{if=Head[#],arg=First[#]},
            MatchQ[Quiet[if["InterpolationOrder"]],{0}] &&
            PolynomialQ[arg,clock] && Exponent[arg,clock]===1 &&
            NumericQ[arg/.clock->0] && NumericQ[D[arg,clock]] && TrueQ[D[arg,clock]!=0]]&],
        Return[$Failed]];
    If[!FreeQ[entries/.HoldPattern[InterpolatingFunction[___][_]]:>0,clock],
        Return[$Failed]];
    interiorMin=Min[N[ta],N[tb]]+10^-14 Abs[N[tb-ta]];
    interiorMax=Max[N[ta],N[tb]]-10^-14 Abs[N[tb-ta]];
    breakpoints=Join@@Map[
        With[{if=Head[#],arg=First[#]},
            b0=N[arg/.clock->0]; b1=N[D[arg,clock]];
            Select[(Flatten[if["Grid"]]-b0)/b1,interiorMin<#<interiorMax&]]&,
        ifCalls];
    knots=DeleteDuplicates[Join[{N[ta],N[tb]},breakpoints]];
    knots=If[tb>=ta,Sort[knots],Reverse[Sort[knots]]];
    If[Length[knots]-1>512,Return[$Failed]];
    gNorm=Normal[generator];
    u=IdentityMatrix[n];
    Do[
        {t0,t1}=knots[[{k,k+1}]];
        dt=t1-t0;
        If[TrueQ[dt==0],Continue[]];
        tMid=(t0+t1)/2;
        gMid=Quiet[Check[N[gNorm/.clock->tMid],$Failed]];
        If[!MatrixQ[gMid,NumericQ],Return[$Failed,Module]];
        stepU=General`Matrices`Private`structuredMatrixExp[dt gMid];
        If[!MatrixQ[stepU,NumericQ],Return[$Failed,Module]];
        u=stepU . u,
        {k,Length[knots]-1}
    ];
    u
];

solveFinalPropagator[generator_,clock_Symbol,interval_,settings_List]:=Module[{n=Length[generator],values,reduce,diagonal},
    values=piecewiseConstantPropagator[generator,clock,interval,settings];
    If[values=!=$Failed,Return[values]];
    reduce=n>1 && canReduceLinearSystemQ[settings];diagonal=reduce && diagonalGeneratorQ[generator];
    If[diagonal,
        values=solveFinalLinearEquation[generator,ConstantArray[1,n],clock,interval,settings];
        If[ListQ[values],Return[SparseArray[Band[{1,1}]->values,{n,n}]]]];
    If[reduce && !diagonal && Head[generator]===SparseArray,
        values=sectorPropagator[generator,clock,interval,settings];
        If[values=!= $Failed,Return[values]]];
    solveFinalLinearEquation[generator,IdentityMatrix[n],clock,interval,settings]
];

singleEnvelopeEvolution[mat_SparseArray,clock_Symbol,{ta_,tb_},settings_List]:=Module[
    {values,unique,factors,env,coeff,position,constant,scale,area,y},
    If[Length[mat]<4 || !exactZeroQ[mat["ImplicitValue"]],Return[$Failed]];
    values=mat["ExplicitValues"];unique=DeleteDuplicates[values];
    If[unique==={} || FreeQ[unique,clock],Return[$Failed]];
    factors=If[Head[#]===Times,List@@#, {#}]& /@ unique;
    env=Times@@Select[First[factors],!FreeQ[#,clock]&];
    If[FreeQ[env,clock] || !AllTrue[Rest[factors],(Times@@Select[#,Function[f,!FreeQ[f,clock]]])===env&],
        Return[$Failed]];
    coeff=(Times@@Select[#,Function[f,FreeQ[f,clock]]])& /@ factors;
    If[!VectorQ[coeff,NumericQ] || !FreeQ[settings,HoldPattern[WorkingPrecision->Except[MachinePrecision]]],
        Return[$Failed]];
    position=mat["ExplicitPositions"];
    constant=SparseArray[MapThread[Rule,{position,Replace[values,Dispatch[MapThread[Rule,{unique,coeff}]],{1}]}],Dimensions[mat]];
    If[!TrueQ[HermitianMatrixQ[constant,Tolerance->0]],Return[$Failed]];
    scale=Norm[constant,Infinity];
    If[!TrueQ[scale>0],Return[$Failed]];
    area=NDSolveValue[{y'[clock]==scale env,y[ta]==0},y[tb],{clock,ta,tb},Evaluate[Sequence@@settings]];
    If[NumericQ[area],General`Matrices`Private`structuredMatrixExp[N[(-I area/scale) constant]],$Failed]
];

(* Adaptive 4th-order Commutator-Free Magnus (2-point Gauss-Legendre) propagator for smooth Hermitian H(t). *)
cf4HamiltonianEvolution[mat_,clock_Symbol,{ta_,tb_},settings_List]:=Module[
    {dim=Length[mat],entries,s,pos,vals,unique,ix,tMid,uMid,hMid,evalH,goals,tol,cf4Run,
     normMid,n0,uCoarse,nSteps,uFine,err,idMat},
    If[dim<2 || dim>64 || !NumericQ[ta] || !NumericQ[tb],Return[$Failed]];
    If[!FreeQ[settings,HoldPattern[WorkingPrecision->Except[MachinePrecision|Automatic]]],Return[$Failed]];
    If[TrueQ[tb==ta],Return[IdentityMatrix[dim]]];
    entries=If[Head[mat]===SparseArray,
        Prepend[mat["ExplicitValues"],mat["ImplicitValue"]],
        mat];
    If[!FreeQ[entries,UnitStep|Piecewise|HeavisideTheta|Boole|If|Which|Switch|InterpolatingFunction|
        Floor|Ceiling|Round|Mod|Sign|Abs|DiracDelta|KroneckerDelta],
        Return[$Failed]];
    s=SparseArray[mat];
    If[!exactZeroQ[s["ImplicitValue"]],Return[$Failed]];
    pos=s["ExplicitPositions"]; vals=s["ExplicitValues"];
    If[pos==={},Return[IdentityMatrix[dim]]];
    unique=DeleteDuplicates[vals];
    ix=Lookup[PositionIndex[unique],vals][[All,1]];
    tMid=N[(ta+tb)/2];
    uMid=Quiet[Check[N[unique/.clock->tMid],$Failed]];
    If[!VectorQ[uMid,NumericQ],Return[$Failed]];
    hMid=Normal[SparseArray[pos->uMid[[ix]],{dim,dim}]];
    If[!HermitianMatrixQ[hMid,Tolerance->10^-11],Return[$Failed]];
    idMat=N[IdentityMatrix[dim]];
    evalH[t_?NumericQ]:=With[{uv=Quiet[Check[N[unique/.clock->t],$Failed]]},
        If[!VectorQ[uv,NumericQ],$Failed,
            Normal[SparseArray[pos->uv[[ix]],{dim,dim}]]]];
    goals=Cases[settings,HoldPattern[(AccuracyGoal|PrecisionGoal)->g_?NumericQ]:>g];
    tol=If[goals==={},10^-8,Min[10^-8,10.^-(Max[goals]-1)]];
    cf4Run[n_Integer]:=Module[
        {h=N[(tb-ta)/n],c1,c2,a1,a2,u=idMat,h1,h2,t0,k},
        c1=(1/2-Sqrt[3]/6) h; c2=(1/2+Sqrt[3]/6) h;
        a1=(1/4-Sqrt[3]/6) h; a2=(1/4+Sqrt[3]/6) h;
        Do[
            t0=N[ta]+k h;
            h1=evalH[t0+c1]; h2=evalH[t0+c2];
            If[h1===$Failed || h2===$Failed,Return[$Failed,Module]];
            u=MatrixExp[-I (a1 h1+a2 h2)] . (MatrixExp[-I (a2 h1+a1 h2)] . u),
            {k,0,n-1}
        ];
        u
    ];
    normMid=Norm[hMid,Infinity]*Abs[N[tb-ta]];
    n0=Max[4,Min[32,2^Ceiling[Log2[Max[4.,2.*normMid]]]]];
    uCoarse=Quiet[Check[cf4Run[n0],$Failed]];
    If[!MatrixQ[uCoarse,NumericQ],Return[$Failed]];
    nSteps=2 n0;
    While[nSteps<=256,
        uFine=Quiet[Check[cf4Run[nSteps],$Failed]];
        If[!MatrixQ[uFine,NumericQ],Return[$Failed]];
        err=Max[Abs[Flatten[uFine-uCoarse]]]/15.;
        If[err<=tol && Max[Abs[Flatten[ConjugateTranspose[uFine] . uFine-idMat]]]<=Max[10^-7,10 tol],
            Return[uFine]];
        uCoarse=uFine;
        nSteps*=2;
    ];
    $Failed
];

finalHamiltonianEvolution[mat_,basis_,clock_Symbol,interval_,settings_List,allowExponential_:True]:=
Module[{blocks,solveBlock,unitaries,envelope,pw,cf4},
    If[TrueQ[allowExponential] && canReduceLinearSystemQ[settings] && Head[mat]===SparseArray,
        envelope=singleEnvelopeEvolution[mat,clock,interval,settings];
        If[envelope=!= $Failed,Return[envelope]]];
    If[canReduceLinearSystemQ[settings] && !diagonalGeneratorQ[mat],
        blocks=separableSpinHamiltonian[mat,basis];
        If[ListQ[blocks],
            solveBlock[b_]:=solveBlock[b]=If[AllTrue[Flatten[b],exactZeroQ],
                IdentityMatrix[Length[b]],solveFinalPropagator[-I b,clock,interval,settings]];
            unitaries=solveBlock /@ blocks;
            If[FreeQ[unitaries,$Failed],Return[KroneckerProduct@@Reverse[unitaries]]]]];
    pw=piecewiseConstantPropagator[-I mat,clock,interval,settings];
    If[pw=!=$Failed,Return[pw]];
    If[TrueQ[allowExponential] && canReduceLinearSystemQ[settings],
        cf4=cf4HamiltonianEvolution[mat,clock,interval,settings];
        If[cf4=!=$Failed,Return[cf4]]];
    solveFinalPropagator[-I mat,clock,interval,settings]
];

