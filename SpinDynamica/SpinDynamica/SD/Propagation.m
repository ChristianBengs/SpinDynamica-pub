AdiabaticPropagationSuperoperator[evals_,evecs_,parametergrid_,timegrid_,spinsys_,opts___Rule]:=Module[
    {vini=First[evecs],vfinal=Last[evecs],dim,projectorRows,paths,evalfuncs,
     evecfuncs,phases,unitary,result},
    CheckAbort[
        dim=Length[vfinal];
        If[TrueQ[DeleteCoherences/.{opts}/.Options[Event]] || dim==1,
            projectorRows[v_]:=SparseArray[Table[
                With[{row=v[[i]]},Flatten[Outer[Times,Conjugate[row],row]]],{i,dim}]];
            result=ConjugateTranspose[projectorRows[vfinal]] . projectorRows[vini],
            paths=phasesmoothing[SparseArray/@#,0]&/@Transpose[evecs];
            vini=SparseArray[Chop[paths[[All,1]]]];
            vfinal=SparseArray[Chop[paths[[All,-1]]]];
            evalfuncs=Interpolation[Transpose[{timegrid,#}]]&/@evals;
            phases=dynamicphase[evalfuncs,dim,{First[timegrid],Last[timegrid]}];
            If[!AllTrue[Flatten@Normal[paths],Internal`RealValuedNumericQ[Chop[#]]&],
                evecfuncs=Interpolation[Transpose[{parametergrid,#}]]&/@paths;
                phases=geometricphase[evecfuncs,dim,parametergrid]*phases
            ];
            unitary=Chop[Transpose[vfinal] . DiagonalMatrix[SparseArray[phases]] . Conjugate[vini]];
            result=SparseArray[KroneckerProduct[unitary,Conjugate[unitary]]]
        ];
        Superoperator[result,ZeemanKetBraOperatorBasis[spinsys]],
        Null
    ]
]


