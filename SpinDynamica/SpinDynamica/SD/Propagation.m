(* For a concrete diagonal Hamiltonian, update only the occupied dyads.
   Both axes use the same working basis as the stored Hamiltonian. *)
staticDiagonalEvolution[state_SparseArray,Event[True|{True,True},{_,_,True,IntegrateEvolutionOverTime,__},
    {Operator[ham_SparseArray,source_,___Rule],dt_?NumericQ},eventOpts___Rule],basis_,opts___Rule]:=
Module[{pos,vals,phase},
    If[source=!=basis || !MatchQ[basis,_ZeemanBasis] || Dimensions[ham]=!=Dimensions[state] ||
        !exactZeroQ[state["ImplicitValue"]] || !diagonalGeneratorQ[ham] || !MatrixQ[ham,NumericQ] ||
        !TrueQ[UseMatrixExpWhenPossible/.{eventOpts,opts}/.Options[NPropagationOperator]] ||
        !TrueQ[(PropagationMethod/.{eventOpts,opts}/.Options[Event])===Automatic],Return[$Failed]];
    pos=state["ExplicitPositions"];If[pos==={},Return[state]];
    vals=state["ExplicitValues"];If[!VectorQ[vals,NumericQ],Return[$Failed]];
    phase=Exp[-I dt N[Normal[Diagonal[ham]]]];
    vals=Chop[vals phase[[pos[[All,1]]]] Conjugate[phase[[pos[[All,2]]]]]];
    SparseArray[MapThread[Rule,{pos,vals}],Dimensions[state]]
];
staticDiagonalEvolution[___]:=$Failed;

(* Fast state-vector / rank-1 dyad and single-spin factored pulse propagation in ZeemanBasis. *)
tryHilbertStatePropagation[rhomat_,events:{_Event..},basis:HoldPattern@ZeemanBasis[spins_?MatrixQ,___Rule],opts___Rule]:=
Module[{dims,d,dyad,u,v,uNorm2,vNorm2,alpha,sameVec,rots,res,tag,state},
    If[!FreeQ[{opts},HoldPattern[WorkingPrecision->Except[MachinePrecision|Automatic]]],Return[$Failed]];
    dims=Round[2 (Last/@spins)+1]; d=Times@@dims;
    If[Dimensions[rhomat]=!={d,d},Return[$Failed]];
    dyad=If[d>=16,General`Matrices`Private`matrixDyadFactors[rhomat],$Failed];
    If[ListQ[dyad] && Length[dyad]===2 && VectorQ[dyad[[1]],NumericQ] && VectorQ[dyad[[2]],NumericQ] &&
        MatchQ[Precision[dyad],Infinity|MachinePrecision],
        {u,v}=N/@dyad;
        uNorm2=Re[Conjugate[u] . u]; vNorm2=Re[Conjugate[v] . v];
        alpha=If[uNorm2>0,(Conjugate[u] . v)/uNorm2,0.];
        sameVec=(uNorm2>0 && vNorm2>0) && (Norm[v-alpha u]<=10^-13 Sqrt[vNorm2]);
        res=Catch[
            Do[
                Which[
                    MatchQ[ev,Event[True|{True,True},{_,_,_,None,__},_,___Rule]] ||
                    MatchQ[ev,Event[True|{True,True},{{T_?NumericQ/;TrueQ[Chop[T]==0],__},_,_,IntegrateEvolutionOverTime,__},{_,_},___Rule]] ||
                    MatchQ[ev,Event[True|{True,True},{_,_,_,InstantaneousTransformation,__},{UnitySuperoperator[___],___},___Rule]] ||
                    MatchQ[ev,Event[True|{True,True},{_,_,_,IntegrateEvolutionOverTime,__},{TimeDependentGeneratorFunction[___,NullGeneratorPattern,___Rule],_},___Rule]],
                    Null,

                    (rots=extractEventRotations[ev,basis])=!=$Failed,
                    With[{blocks=zeemanPulseBlocks[rots,spins]},
                        If[blocks===$Failed,Throw[$Failed,tag]];
                        u=applyFactoredPulseToStateVector[u,blocks,dims];
                        If[!VectorQ[u,NumericQ],Throw[$Failed,tag]];
                        If[!sameVec,
                            v=applyFactoredPulseToStateVector[v,blocks,dims];
                            If[!VectorQ[v,NumericQ],Throw[$Failed,tag]]]],

                    MatchQ[ev,Event[True|{True,True},{_,_,True,IntegrateEvolutionOverTime,__},{_,_?NumericQ},___Rule]],
                    Module[{gen=ev[[3,1]],dt=ev[[3,2]],evOpts=Sequence@@Drop[ev,3],hop,hopEval,x,evals,xi,weights,hmat,amat,uNew,vNew,uMat},
                        If[!TrueQ[UseMatrixExpWhenPossible/.{evOpts,opts}/.Options[NPropagationOperator]] ||
                            !TrueQ[(PropagationMethod/.{evOpts,opts}/.Options[Event])===Automatic],
                            Throw[$Failed,tag]];
                        hop=Switch[gen,
                            HoldPattern@CommutationSuperoperator[_?OperatorQ,___Rule], I First[gen],
                            _?OperatorQ, gen,
                            _, Throw[$Failed,tag]];
                        hopEval=hop/.{evOpts,opts};
                        If[MatchQ[hopEval,HoldPattern@Operator[{_?MatrixQ,_List,_?MatrixQ},b1_,___Rule]/;b1===basis],
                            {x,evals,xi}=First[hopEval];
                            If[!MatrixQ[x,NumericQ] || !VectorQ[evals,NumericQ] || !MatrixQ[xi,NumericQ] || Length[evals]=!=d,
                                Throw[$Failed,tag]];
                            weights=Exp[-I dt N[evals]];
                            u=N[x] . (weights*Normal[N[xi] . u]);
                            If[!sameVec,v=N[x] . (weights*Normal[N[xi] . v])],
                            hmat=MatrixRepresentation[hopEval,basis];
                            If[!MatrixQ[hmat,NumericQ] || Dimensions[hmat]=!={d,d} || !MatchQ[Precision[hmat],Infinity|MachinePrecision],
                                Throw[$Failed,tag]];
                            Which[
                                diagonalGeneratorQ[hmat],
                                weights=Exp[-I dt N[Normal[Diagonal[hmat]]]];
                                u=weights*u;
                                If[!sameVec,v=weights*v],
                                (sameVec && d>=64) || d>=128,
                                amat=-I dt N[hmat];
                                uNew=Quiet[Check[MatrixExp[amat,u,Method->{"Krylov",Tolerance->10^-12}],$Failed]];
                                If[VectorQ[uNew,NumericQ],
                                    u=uNew;
                                    If[!sameVec,
                                        vNew=Quiet[Check[MatrixExp[amat,v,Method->{"Krylov",Tolerance->10^-12}],$Failed]];
                                        If[!VectorQ[vNew,NumericQ],Throw[$Failed,tag]];
                                        v=vNew],
                                    uMat=General`Matrices`Private`structuredMatrixExp[amat];
                                    If[!MatrixQ[uMat,NumericQ],Throw[$Failed,tag]];
                                    u=uMat . u; If[!sameVec,v=uMat . v]],
                                True,
                                uMat=General`Matrices`Private`structuredMatrixExp[-I dt N[hmat]];
                                If[!MatrixQ[uMat,NumericQ],Throw[$Failed,tag]];
                                u=uMat . u; If[!sameVec,v=uMat . v]
                            ]
                        ]],

                    True,
                    Throw[$Failed,tag]
                ],
                {ev,Reverse[events]}
            ];
            If[sameVec,v=alpha*u];
            Chop[Outer[Times,u,Conjugate[v]]],
            tag
        ];
        Return[res]
    ];
    (* For full-rank states under pure 1-spin selective pulses on D<=32, contract in-place without D x D Kron. *)
    If[d<=32 && MatrixQ[rhomat,NumericQ] && MatchQ[Precision[rhomat],Infinity|MachinePrecision],
        res=Catch[
            state=rhomat;
            Do[
                With[{rots=extractEventRotations[ev,basis]},
                    If[rots===$Failed,Throw[$Failed,tag]];
                    With[{blocks=zeemanPulseBlocks[rots,spins]},
                        If[blocks===$Failed || Count[blocks,Except[None]]>1,Throw[$Failed,tag]];
                        state=applyFactoredPulseToDensityMatrix[state,blocks,dims];
                        If[!MatrixQ[state,NumericQ],Throw[$Failed,tag]]]],
                {ev,Reverse[events]}
            ];
            Chop[state],
            tag
        ];
        If[res=!=$Failed,Return[res]]
    ];
    $Failed
];
