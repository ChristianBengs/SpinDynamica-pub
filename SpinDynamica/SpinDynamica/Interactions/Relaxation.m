(* ::Input::Initialization:: *)
singleSpinRelaxCounts[{j_,Ij_}]:=singleSpinRelaxCounts[{j,Ij}]=Module[
    {ops=QM`Liouville`Private`SingleSpinShiftAndZBasisOperators[{j,Ij}]},
    Map[Function[op,With[{eop=Expand[op]},
        {
            Count[{eop},HoldPattern[opI[j,"z",___]],Infinity],
            Count[{eop},HoldPattern[opI[j,"+",___]],Infinity]+Count[{eop},HoldPattern[opI[j,"-",___]],Infinity],
            If[Head[eop]===Plus,Length[eop],1]
        }]],ops]
];

PhenomenologicalRelaxationSuperoperator[jT1T2list:{{_,_,_}..},opts___Rule]:=
Module[{sys=SpinSystem[],spins,spinsmissing,jT1T2list$,r1Map,r2Map,perSpinRM,combined,diagOrd,perm,diagCoh,nL},(
spins=First/@sys;
spinsmissing=Complement[spins,jT1T2list[[All,1]]];
jT1T2list$=Join[jT1T2list,{#,\[Infinity],\[Infinity]}&/@spinsmissing];
r1Map=Association[#->1/FirstCase[jT1T2list$,{#,_,_}][[2]]&/@spins];
r2Map=Association[#->1/FirstCase[jT1T2list$,{#,_,_}][[3]]&/@spins];
perSpinRM=Function[spin,
    With[{j=First[spin],counts=singleSpinRelaxCounts[spin],r1=r1Map[First[spin]],r2=r2Map[First[spin]]},
        {-(#[[1]]*r1+#[[2]]*r2),#[[3]]}&/@counts
    ]]/@Reverse[sys];
combined=Fold[
    Function[{acc,next},
        With[{rA=acc[[1]],mA=acc[[2]],rB=next[[All,1]],mB=next[[All,2]]},
            If[mA===1 && AllTrue[mB,#===1&],
                {Flatten[Outer[Plus,rA,rB]],1},
                With[{mAvec=If[ListQ[mA],mA,ConstantArray[1,Length[rA]]]},
                    {
                        Flatten[Outer[Times,rA,mB]+Outer[Times,mAvec,rB]],
                        Flatten[Outer[Times,mAvec,mB]]
                    }
                ]
            ]
        ]],
    {perSpinRM[[1,All,1]],If[AllTrue[perSpinRM[[1,All,2]],#===1&],1,perSpinRM[[1,All,2]]]},
    Rest[perSpinRM]
];
diagOrd=First[combined];
perm=QM`Liouville`Private`ShiftAndZCoherenceOrderPermutation[sys];
diagCoh=diagOrd[[perm]];
nL=Length[diagCoh];
Superoperator[SparseArray[Band[{1,1}]->diagCoh,{nL,nL}],ShiftAndZOperatorBasis[]]
)];


