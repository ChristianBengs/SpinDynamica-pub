(* ::Input::Initialization:: *)
amplitudeTableRanges[total_,limit_,kernels_]:=Module[{size},
    size=Min[limit,If[kernels>0,Ceiling[total/(4 kernels)],total]];
    Table[{start,Min[start+size-1,total]},{start,1,total,size}]
];


(* ::Input::Initialization:: *)
(* Point-major intervals let a worker return one weighted sum per point it touches. *)
amplitudeTableBlock[{lo_,hi_},points_,samples_,vars_,compute_]:=Module[
    {n=Length[samples],offset,tableRules,amplitude,failed},
    Catch[Table[
        offset=(point-1) n;
        tableRules=MapThread[Rule,{Take[vars,Length[points[[point]]]],points[[point]]}];
        {point,Total[Table[
            amplitude=compute[Join[tableRules,
                MapThread[Rule,{Drop[vars,Length[tableRules]],First[samples[[j]]]}]]];
            If[!FreeQ[amplitude,$Failed|$Aborted],Throw[$Failed,failed]];
            Last[samples[[j]]] amplitude,
            {j,Max[1,lo-offset],Min[n,hi-offset]}]]},
        {point,Quotient[lo-1,n]+1,Quotient[hi-1,n]+1}],failed]
];


(* ::Input::Initialization:: *)
amplitudeTableResult[parts_,coords_]:=
    formatAmplitudeTable[(Total[Last/@#]&)/@SplitBy[Join@@parts,First],coords];

formatAmplitudeTable[input_,coords_]:=Module[{values=input,order,labels,output},
    If[coords=!=None,
        order=SortBy[Range[Length[coords]],{N[coords[[#]]],#}&];
        labels=coords[[order]]; values=values[[order]]];
    output=Table[If[coords===None,values[[All,k]],MapThread[Append,{labels,values[[All,k]]}]],
        {k,Length[First[values]]}];
    If[Length[output]===1,First[output],output]
];


