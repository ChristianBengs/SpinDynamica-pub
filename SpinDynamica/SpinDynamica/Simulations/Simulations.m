    Superoperator,dim=BasisDimension[basis]^2;(SuperoperatorMatrixRepresentation[#,opbasis]&),
    Operator,dim=BasisDimension[basis];(MatrixRepresentation[#,basis]&)
];
Sjset=Join@@MapThread[If[#1>0,ConstantArray[represent[#2],#1],{}]&,{nreps,props}];
FoldList[
Dot[#2,#1]&,
IdentityMatrix[dim,SparseArray],
Reverse@Sjset]
)/;(
evbackg=BackgroundGenerator/.{opts}/.Options[DividedEventPropagators];
standevbackg=StandardizeGenerator[evbackg];
MatchQ[standevbackg,_?OperatorQ|_?SuperoperatorQ|NullGeneratorPattern]
)
];


