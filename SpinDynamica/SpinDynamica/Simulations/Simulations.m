\[Lambda]vals=-Re/@zvals;
peaks=Transpose[{avals,\[Omega]vals,\[Lambda]vals}];
Signal[{tmin,tmax,\[Delta]t},{"Lorentzian",peaks},
SimplifyRules[
Sequence@@FilterRules[
Join[{opts},Options@Signal1D],
Options[Signal]
]
]
]
)];


