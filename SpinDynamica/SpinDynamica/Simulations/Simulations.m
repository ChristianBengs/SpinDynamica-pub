(* In a commutator eigenmode the excitation and detection coefficients are dual Hilbert matrices. *)
HoldPattern@commutatorSignalPeaks[CommutationSuperoperator[op_,___Rule],rho_,detector_,basis_,norm_,opts___Rule]:=
Module[{diagonal,x,values,xi,r,q,excitation,detection,amplitudes,rates},
    diagonal=NDiagonalize[op,basis,opts];
    If[!MatchQ[diagonal,HoldPattern@Operator[{_?MatrixQ,_List,_?MatrixQ},_,___]],Return[$Failed]];
    {x,values,xi}=First[diagonal];
    r=MatrixRepresentation[rho,basis]; q=MatrixRepresentation[detector,basis];
    If[!MatrixQ[r,NumericQ] || !MatrixQ[q,NumericQ],Return[$Failed]];
    excitation=Normal[xi . r . x];
    detection=Normal[Transpose[xi . ConjugateTranspose[q] . x]];
    amplitudes=Chop[Flatten[detection excitation]]/(norm Norm[Flatten[Normal[q]]]^2);
    rates=Flatten[Outer[Subtract,values,values]];
    Transpose[{amplitudes,Im[rates],-Re[rates]}]
];
commutatorSignalPeaks[Verbatim[Superoperator][csop_CommutationSuperoperator,___],args___]:=commutatorSignalPeaks[csop,args];
commutatorSignalPeaks[___]:=$Failed;


