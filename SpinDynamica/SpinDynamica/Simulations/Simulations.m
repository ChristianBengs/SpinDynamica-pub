(* A new event resets local generator clocks. Only combine option-free static
   intervals when the background is known to be static as well. *)
combineAcquisitionIntervals[events_,background_]:=Module[{sameStaticInterval},
    If[!TrueQ[background===None || OperatorQ[background] || SuperoperatorQ[background]],Return[events]];
    sameStaticInterval[a_,b_]:=MatchQ[a,{_,_?NumericQ}] && MatchQ[b,{_,_?NumericQ}] &&
        First[a]===First[b] && TrueQ[First[a]===None || OperatorQ[First[a]] || SuperoperatorQ[First[a]]];
    (If[Length[#]==1,First[#],{#[[1,1]],Total[#[[All,2]]]}]& /@ Split[events,sameStaticInterval])
];

