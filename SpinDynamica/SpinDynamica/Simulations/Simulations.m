HoldPattern@ConvertOperatorTrajectoryFunctionToTrajectoryFunction[
    OperatorTrajectoryFunction[timing_,f:Verbatim[Function][_,_],more___],obsop_?OperatorQ,opts___Rule]:=
With[{norm=NormalizationFactor/.{opts}/.{NormalizationFactor->1},
      obsnorm=LiouvilleBracket[obsop,obsop]},
    Module[{operators,amplitudes},
        operators=DeleteDuplicates[Cases[f,_Operator,Infinity]];
        amplitudes=Function[op,With[{amplitude=ExpToTrig[(LiouvilleBracket[obsop,op]/obsnorm)/norm]},
            If[FreeQ[amplitude,Cosh|Sinh],amplitude,TrigToExp[amplitude]]]]/@operators;
        TrajectoryFunction[timing,f/.Dispatch[MapThread[Rule,{operators,amplitudes}]]]]
];

HoldPattern@trajectoryReadouts[ot:OperatorTrajectoryFunction[timing_,f:Verbatim[Function][_,_],___],ops:{_,__},opts___Rule]/;
    ({Method,Normalize}/.Options[LiouvilleBracket])==={Automatic,False}:=
Module[{states,vectors,detectors,ob,basis,norm},
    states=DeleteDuplicates[Cases[f,_Operator,Infinity]];
    ob=ZeemanKetBraOperatorBasis[Sorted->"Canonical"]; basis=ZeemanBasis[];
    vectors=OperatorVectorRepresentation[#,ob,basis]& /@ states;
    detectors=OperatorVectorRepresentation[#,ob,basis]& /@ ops;
    If[!AllTrue[Join[vectors,detectors],VectorQ],
        Return[ConvertOperatorTrajectoryFunctionToTrajectoryFunction[ot,#,opts]& /@ ops]];
    norm=NormalizationFactor/.{opts}/.{NormalizationFactor->1};
    Function[det,Module[{bra=Adjoint[det],self,amplitudes},
        self=Simplify[bra . det];
        amplitudes=Function[v,With[{a=ExpToTrig[(Simplify[bra . v]/self)/norm]},
            If[FreeQ[a,Cosh|Sinh],a,TrigToExp[a]]]] /@ vectors;
        TrajectoryFunction[timing,f/.Dispatch[MapThread[Rule,{states,amplitudes}]]]]] /@ detectors
];
trajectoryReadouts[ot_,ops_List,opts___Rule]:=ConvertOperatorTrajectoryFunctionToTrajectoryFunction[ot,#,opts]& /@ ops;



