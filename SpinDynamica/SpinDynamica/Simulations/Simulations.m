   the implicit value. A sparse numeric Hamiltonian is a common fixed option. *)
amplitudeIndependentQ[expr_,vars_List]:=With[{pat=Alternatives@@vars},
    FreeQ[expr,pat] && AllTrue[Cases[expr,a_SparseArray:>a,{0,Infinity}],
        FreeQ[{#["ExplicitValues"],#["ImplicitValue"]},pat]&]
];

(* Eigensystem returns eigenvectors as rows. If all operators are dyads,
   use two state-vector overlaps per detector. Otherwise use energy gaps. *)
coherentDelayValues[ham_,rho_,detectors_,before_,after_,times_List,denominators_List,limit_:Infinity]:=
Module[{energy,rows,v,left,right,initial,dyad,obs,split,coeffRows,coefficients,freq,size,one,finish,parts},
    If[!TrueQ[HermitianMatrixQ[ham,Tolerance->0]],Return[$Failed]];
    If[AnyTrue[Join[{ham,rho,before,after},detectors,times,denominators],
        !MatchQ[Precision[#],Infinity|MachinePrecision]&],Return[$Failed]];
    If[TrueQ[DiagonalMatrixQ[ham,Tolerance->0]],
        energy=N[Normal[Diagonal[ham]]];left=after;right=before,
        {energy,rows}=Eigensystem[N[Normal[ham]]];
        If[!VectorQ[energy,NumericQ] || !MatrixQ[rows,NumericQ],Return[$Failed]];
        v=Transpose[rows];right=ConjugateTranspose[v] . before;left=after . v];
    dyad=General`Matrices`Private`matrixDyadFactors[rho];
    obs=If[ListQ[dyad],General`Matrices`Private`matrixDyadFactors/@detectors,$Failed];
    If[ListQ[obs] && FreeQ[obs,$Failed],
        split=Length[obs];initial=(right . #)& /@ dyad;
        coeffRows=Join@@Table[(Normal[(Conjugate[#[[k]]] . left) initial[[k]]]& /@ obs),{k,2}];
        (* Subtracting an energy origin cancels a common phase in both overlaps. *)
        freq=energy-First[energy];
        finish[x_]:=Take[x,split] Conjugate[Drop[x,split]],
        initial=right . rho . ConjugateTranspose[right];
        coeffRows=Normal[Flatten[Conjugate[ConjugateTranspose[left] . # . left] initial]]& /@ detectors;
        freq=Flatten[Outer[Subtract,energy,energy]];
        finish[x_]:=x];
    coefficients=N[If[Length[coeffRows]===1,List/@First[coeffRows],Transpose[coeffRows]]];
    size=Min[limit,Max[1,Quotient[262144,Length[freq]]]];
    one[ts_]:=(Chop[N[finish[#]/denominators]]& /@ (Exp[-I Outer[Times,N[ts],freq]] . coefficients));
    parts=Table[one[Take[times,{i,Min[i+size-1,Length[times]]}]],{i,1,Length[times],size}];
    Join@@parts
];

coherentDelayTable[initial_,obs_,events_,variable_Symbol,times_List,settings_List,limit_]:=
Module[{norm,ob,basis,prop,back,chron,spec,items,ix,index,fixed,probe,evlist,evs,middle,
        zb,ham,rho,det,denom,dimension,unitary,before,after},
    {norm,ob,basis,prop}=settings;
    If[!NumericQ[norm] || TrueQ[norm==0] ||
        !MatchQ[ob,HoldPattern@ZeemanKetBraOperatorBasis[_,Sorted->"Canonical"]] ||
        !TrueQ[QM`Hilbert`Private`CheckedBasisQ[basis]] || SpinSystem[ob]=!=SpinSystem[basis] ||
        !(And@@(TrueQ[NumericQ[#] && Im[#]==0 && #>=0]& /@ times)),Return[$Failed]];
    {back,chron}={BackgroundGenerator,Chronology}/.prop/.Options[NPropagate];
    If[!TrueQ[(UseHilbertSpaceWhenPossible/.prop/.Options[NPropagate])===True &&
        (UseMatrixExpWhenPossible/.prop/.Options[NPropagate])===True] ||
        TrueQ[(UseDiagonalizationWhenPossible/.prop/.Options[NPropagate])===False] ||
        !MatchQ[back,None|NullGeneratorPattern|_?OperatorQ] ||
        !FreeQ[{back,events},_TimeDependentGeneratorFunction|_PeriodicGeneratorFunction|_InterpolatingFunction|
            _PrecalculatedEvent|_Repeat|_RuleDelayed] ||
        !FreeQ[prop,HoldPattern[WorkingPrecision->Except[MachinePrecision]]] ||
        !FreeQ[prop,HoldPattern[(StepMonitor|EvaluationMonitor|Method|PropagationMethod)->Except[None|Automatic]]],
        Return[$Failed]];
    spec=EventSpecifications[events,Chronology->chron];
    If[!MatchQ[spec,HoldPattern@EventSpecifications[True,{__},___Rule]],Return[$Failed]];
    items=spec[[2]];
    ix=Select[Range[Length[items]],MatchQ[items[[#]],{_,variable,___Rule}]&];
    If[Length[ix]=!=1,Return[$Failed]];index=First[ix];
    fixed=Delete[items,index];
    If[!amplitudeIndependentQ[{fixed,Delete[items[[index]],2]}, {variable}] ||
        !MatchQ[First[items[[index]]],None|NullGeneratorPattern|_?OperatorQ] ||
        !AllTrue[fixed,MatchQ[#,{_RotationSuperoperator|_UnitySuperoperator|HoldPattern[Dot[_RotationSuperoperator..]],___Rule}|
            {None|NullGeneratorPattern|_?OperatorQ,_?NumericQ,___Rule}]&] ||
        !FreeQ[items,HoldPattern[(UseMatrixExpWhenPossible|UseHilbertSpaceWhenPossible|UseDiagonalizationWhenPossible)->False]] ||
        !FreeQ[items,HoldPattern[(PropagationMethod|PropagatorCalculationProcedure)->Except[Automatic]]],Return[$Failed]];
    probe=SelectFirst[times,TrueQ[Chop[#]>0]&,0];If[probe===0,Return[$Failed]];
    evlist=EventList[ReplaceEverywhere[spec,variable->probe],
        SimplifyRules[Chronology->chron,BackgroundGenerator->back,ImplementBackgroundGenerator->True,
            ExpandRepeatedEvents->False,Sequence@@FilterRules[Join[prop,Options[NPropagate]],Join[Options[EventList],Options[NDSolve]]]]];
    If[!MatchQ[evlist,HoldPattern@EventList[True|{True,True},_,{__Event},___Rule]],Return[$Failed]];
    evs=evlist[[3]];
    If[Length[evs]=!=Length[items] || !AllTrue[evs,TrueQ[HilbertSpaceCompatibility[#]]&],Return[$Failed]];
    middle=evs[[index]];
    If[PropagatorCalculationProcedure[middle]=!=IntegrateEvolutionOverTime ||
        !TrueQ[BackgroundGeneratorImplemented[middle]] ||
        !MatchQ[middle[[3]],{_?OperatorQ,_?NumericQ}] || !TrueQ[middle[[3,2]]==probe],Return[$Failed]];
    zb=ZeemanBasis[SpinSystem[basis]];dimension=BasisDimension[zb];
    If[dimension>256,Return[$Failed]];
    ham=MatrixRepresentation[middle[[3,1]],zb];
    If[!MatrixQ[ham,NumericQ] || !TrueQ[HermitianMatrixQ[ham,Tolerance->0]],Return[$Failed]];
    rho=MatrixRepresentation[initial,zb];det=MatrixRepresentation[#,zb]& /@ obs;
    denom=norm If[SpinSystem[Basis[]]===SpinSystem[zb] && TrueQ[QM`Hilbert`Private`CheckedBasisQ[Basis[]]],
        (Norm[Flatten[#]]^2& /@ det),(OperatorNorm[#]^2& /@ obs)];
    If[!MatrixQ[rho,NumericQ] || !AllTrue[det,MatrixQ[#,NumericQ]&] ||
        !AllTrue[denom,NumericQ[#] && !TrueQ[#==0]&],Return[$Failed]];
    unitary[{}]:=IdentityMatrix[dimension,SparseArray];
    unitary[seq_List]:=With[{mats=MatrixRepresentation[NPropagationOperator[True,False,#,zb,Sequence@@prop],zb]& /@ seq},
        If[AllTrue[mats,MatrixQ[#,NumericQ]&],Fold[Dot,First[mats],Rest[mats]],$Failed]];
    before=unitary[Drop[evs,index]];after=unitary[Take[evs,index-1]];
    If[MemberQ[{before,after},$Failed],Return[$Failed]];
    coherentDelayValues[ham,rho,det,before,after,If[TrueQ[Chop[#]==0],0,#]& /@ times,denom,limit]
];

TransformationAmplitudeTable[True,{True,True,False},initial_,obs_,events_,iterlists_,opts___Rule]:=
Module[{ens,tabvars,coords,limit,parallel,points,samples,vars,total,bases,fixedBases,
        template,detectors,fixedSettings,fixedInitial,fixedObs,fixedEvents,sendGlobals,worker,ranges,parts,fast},
    {ens,tabvars,coords,limit,parallel}={EnsembleAverage,TableVariables,TableCoordinates,MaxBatchSize,Parallel}/.
        {opts}/.Options[TransformationAmplitudeTable];
    If[!(limit===Infinity || (IntegerQ[limit] && limit>0)),Message[TransformationAmplitudeTable::batchsize];Return[$Failed]];
    points=Flatten[Table[tabvars,Evaluate[Sequence@@iterlists]],Length[tabvars]-1];
    samples=Last[ens]; vars=Join[tabvars,First[ens]];
    total=Length[points] Length[samples];
    If[total===0,Return[{}]];
    (* Exclude the full coordinate and ensemble tables before any per-sample replacement. *)
    template=SimplifyRules[FilterRules[Join[{EnsembleAverage->None,opts},
        CurrentOptionsToPassDown[TransformationAmplitudeTable,TransformationAmplitude]],
        Join[Options[TransformationAmplitude],Options[NPropagate],Options[NDSolve]]]];
    bases={OperatorBasis,Basis}/.template/.Options[TransformationAmplitude];
    fixedBases=FreeQ[template,HoldPattern[RuleDelayed[OperatorBasis|Basis,_]]] && amplitudeIndependentQ[bases,vars];
    fixedInitial=amplitudeIndependentQ[initial,vars];fixedObs=amplitudeIndependentQ[obs,vars];
    fixedSettings=FreeQ[template,_RuleDelayed] && amplitudeIndependentQ[template,vars];
    If[Length[points]>=4 && Length[tabvars]===1 && MatchQ[First[tabvars],_Symbol] &&
        Length[samples]===1 && TrueQ[Last[First[samples]]==1] && fixedInitial && fixedObs && fixedSettings &&
        amplitudeIndependentQ[events,First[ens]] && !FreeQ[events,First[tabvars]],
        fast=coherentDelayTable[initial,obs,events,First[tabvars],First/@points,amplitudeSettings[template],limit];
        If[ListQ[fast],Return[formatAmplitudeTable[fast,coords]]]];
    fixedEvents=amplitudeIndependentQ[events,vars];
    detectors=If[fixedBases && fixedObs,amplitudeDetectors[obs,First[bases],Last[bases]],Automatic];
    If[detectors===$Failed,Return[$Failed]];
    With[{grid=points,ensemble=samples,variables=vars,rows=detectors,
          initialFor=If[fixedInitial,Function[r,initial],Function[r,ReplaceEverywhere[initial,r]]],
          obsFor=If[fixedObs,Function[r,obs],Function[r,ReplaceEverywhere[obs,r]]],
          eventsFor=If[fixedEvents,Function[r,events],Function[r,ReplaceEverywhere[events,r]]],
          settingsFor=If[fixedSettings,With[{frozen=amplitudeSettings[template]},Function[rules,frozen]],
              With[{input=template},Function[rules,amplitudeSettings[ReplaceEverywhere[input,rules]]]]]},
        worker[range_]:=amplitudeTableBlock[range,grid,ensemble,variables,
            Function[rules,transformationAmplitudeValues[initialFor[rules],obsFor[rules],eventsFor[rules],
                rows,settingsFor[rules]]]]];
    parallel=MatchQ[parallel,True|All|_?NumericQ] && total>1;
    If[parallel,
        sendGlobals=DistributeGlobalDefinitions/.{opts}/.Options[TransformationAmplitudeTable];
        If[If[fixedBases,PrepareParallel[First[bases],Last[bases],DistributeGlobalDefinitions->sendGlobals,opts],
            PrepareParallel[OperatorBasis[],Basis[],DistributeGlobalDefinitions->sendGlobals,opts]]===$Failed,Return[$Failed]]];
    ranges=amplitudeTableRanges[total,limit,If[parallel,Max[1,$KernelCount],0]];
    parts=If[parallel,
        Internal`WithLocalSettings[DistributeDefinitions[worker],ParallelMap[worker,ranges],ClearDistributedDefinitions[worker]],
        Map[worker,ranges]];
    If[!FreeQ[parts,$Failed|$Aborted],$Failed,amplitudeTableResult[parts,coords]]
];

