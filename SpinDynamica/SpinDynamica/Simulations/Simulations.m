compileAffineEnsembleSpecs[events_Hold,pointOptions_Hold,vars_List,basis_]:=Module[
    {entries=<||>,compileOp,newEvents,newOptions},
    compileOp[op_]:=Module[{mat,decomp,sym},
        If[!OperatorQ[op] || MatchQ[op,_UnityOperator|_NullOperator|_Operator] ||
            !FreeQ[op,_TimeDependentGeneratorFunction|_Function|_InterpolatingFunction] ||
            FreeQ[op,Alternatives@@vars],
            Return[op]];
        If[KeyExistsQ[entries,Hold[op]],Return[entries[Hold[op]]["Symbol"]]];
        mat=Quiet[Check[MatrixRepresentation[op,basis],$Failed]];
        decomp=General`Matrices`Private`decomposeSymbolicMatrix[mat,vars];
        If[!AssociationQ[decomp],Return[op]];
        sym=Unique["SD`AffineOp$"];
        entries[Hold[op]]=<|"Symbol"->sym,"Decomp"->decomp|>;
        sym
    ];
    newEvents=Replace[events,{
        HoldPattern[CommutationSuperoperator[op_?OperatorQ,cOpts___Rule]]:>
            With[{cOp=compileOp[op]},CommutationSuperoperator[cOp,cOpts]/;True],
        HoldPattern[{op_?OperatorQ,dur_,evOpts___Rule}]:>
            With[{cOp=compileOp[op]},{cOp,dur,evOpts}/;True],
        HoldPattern[{op_?OperatorQ}]:>
            With[{cOp=compileOp[op]},{cOp}/;True]
    },{1,Infinity}];
    newOptions=Replace[pointOptions,{
        HoldPattern[BackgroundGenerator->{det_,prep_}]:>
            With[{cDet=compileOp[det],cPrep=compileOp[prep]},(BackgroundGenerator->{cDet,cPrep})/;True],
        HoldPattern[BackgroundGenerator->det_]:>
            With[{cDet=compileOp[det]},(BackgroundGenerator->cDet)/;True]
    },{1}];
    {newEvents,newOptions,Values[entries]}
];

signalEnsembleSamples[timing_,events_Hold,settings_Hold,ensemble_,opbasis_,basis_,parallel_]:=Module[
    {rules=EnsembleSubstitutionRules[ensemble],vars=If[ListQ[First[ensemble]],Select[First[ensemble],MatchQ[#,_Symbol]&],{}],
     compiled={},evHold,pointHold,worker,i},
    With[{pointOptions=DeleteCases[settings,
            HoldPattern[Rule[EnsembleAverage,_]|RuleDelayed[EnsembleAverage,_]],{1}]},
        If[!parallel && vars=!={},
            {evHold,pointHold,compiled}=compileAffineEnsembleSpecs[events,pointOptions,vars,basis]];
        worker=If[compiled==={},
            Function[sample,
                Signal1D[True,timing,Evaluate[ReleaseHold[ReplaceEverywhere[events,sample]]],
                    Evaluate[SimplifyRules[EnsembleAverage->False,OperatorBasis->opbasis,Basis->basis,
                        Sequence@@Apply[List,ReplaceEverywhere[pointOptions,sample]],WarnAboutMissingPreparationBackground->False]]]],
            With[{evIn=evHold,ptIn=pointHold,compIn=compiled,varsIn=vars},
                Function[sample,
                    With[{subRules=Map[(#["Symbol"]->Operator[General`Matrices`Private`evaluateAffineMatrix[#["Decomp"],varsIn/.sample],basis,CheckOperatorType->False,CheckMatrixDimensions->False])&,compIn]},
                        Signal1D[True,timing,Evaluate[ReleaseHold[ReplaceEverywhere[evIn/.subRules,sample]]],
                            Evaluate[SimplifyRules[EnsembleAverage->False,OperatorBasis->opbasis,Basis->basis,
                                Sequence@@Apply[List,ReplaceEverywhere[ptIn/.subRules,sample]],WarnAboutMissingPreparationBackground->False]]]]]]
        ]
    ];
    If[parallel,
        ParallelMap[Evaluate[worker],rules,Method->"CoarsestGrained",DistributedContexts->"Global`"],
        Monitor[Table[worker[rules[[i]]],{i,Length[rules]}],ProgressIndicator[i,{1,Length[rules]+1}]]]
];

