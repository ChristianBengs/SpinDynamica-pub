(* ::Input::Initialization:: *)
amplitudeDetectors[ops_,opbasis_,basis_]:=Module[{vectors,norms,rows},
    vectors=OperatorVectorRepresentation[#,opbasis,basis]& /@ ops;
    If[!FreeQ[vectors,$Failed],Return[$Failed]];
    norms=If[MatchQ[opbasis,HoldPattern@ZeemanKetBraOperatorBasis[_,Sorted->"Canonical"]] &&
        SameQ[SpinSystem[opbasis],SpinSystem[Basis[]]] && TrueQ[QM`Hilbert`Private`CheckedBasisQ[Basis[]]] &&
        AllTrue[vectors,VectorQ[#,NumericQ]&],
        (Norm[#]^2& /@ vectors),(OperatorNorm[#]^2& /@ ops)];
    rows=Conjugate[vectors];
    If[Length[rows]>1 && AnyTrue[rows,Head[#]===SparseArray&],
        rows=If[AllTrue[rows,Head[#]===SparseArray&],SparseArray[rows],Normal/@rows]];
    {rows,norms}
];

amplitudeSettings[options_List]:=Module[{norm,ob,basis,pass,propagation},
    {norm,ob,basis}={NormalizationFactor,OperatorBasis,Basis}/.options/.Options[TransformationAmplitude];
    pass=CurrentOptionsToPassDown[TransformationAmplitude,NPropagate];
    propagation=Join[{OperatorBasis->ob,Basis->basis},
        FilterRules[SimplifyRules[Join[{Continuous->False},options,pass]],Join[Options[NPropagate],Options[NDSolve]]],options];
    {norm,ob,basis,propagation}
];

transformationAmplitudeValues[initial_,ops_,events_,prepared_,{norm_,ob_,basis_,propOptions_List}]:=
Module[{final,vector,detectors},
    final=NPropagate[events,Sequence@@propOptions][initial];
    If[!FreeQ[final,$Failed],Return[$Failed]];
    vector=OperatorVectorRepresentation[final,ob,basis];
    detectors=If[prepared===Automatic,amplitudeDetectors[ops,ob,basis],prepared];
    If[!FreeQ[{detectors,vector},$Failed],Return[$Failed]];
    With[{rows=First[detectors],norms=Last[detectors]},
        Chop[N[If[Length[norms]===1,{First[rows] . vector},Normal[rows . vector]]/(norm norms)]]]

];

TransformationAmplitude[True,True,True,initial_,ops_List,events_,opts___Rule]:=
    transformationAmplitudeValues[initial,ops,events,Automatic,amplitudeSettings[{opts}]];


